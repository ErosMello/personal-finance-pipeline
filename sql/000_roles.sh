#!/usr/bin/env bash
# Cria as roles e o schema antes de carregar o modelo.
set -eu

: "${FINANCE_APP_PASSWORD:?Defina FINANCE_APP_PASSWORD}"
: "${FINANCE_BI_PASSWORD:?Defina FINANCE_BI_PASSWORD}"

psql --set ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<'SQL'
\getenv app_password FINANCE_APP_PASSWORD
\getenv bi_password FINANCE_BI_PASSWORD
CREATE ROLE finance_owner NOLOGIN
  NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE finance_app LOGIN PASSWORD :'app_password'
  NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE finance_bi LOGIN PASSWORD :'bi_password'
  NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE SCHEMA fin AUTHORIZATION finance_owner;
SQL
